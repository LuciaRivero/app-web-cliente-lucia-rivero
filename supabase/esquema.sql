-- =========================================================
-- Whiplash — Esquema de Supabase
-- Ejecutar completo en el SQL Editor del proyecto. Se puede
-- volver a ejecutar: crea lo que falta y actualiza los datos.
--
-- - generos, artistas y productos: el catálogo del sitio.
--   Lectura pública. Los productos los carga, edita y borra
--   solo un administrador (pages/admin.html).
-- - seguidos y carrito_items: datos de cada usuario de
--   Supabase Auth. Cada uno ve y edita solo sus filas (RLS).
-- - Bucket "productos" de Storage: imágenes de los productos.
--   Lectura pública, escritura solo para administradores.
--
-- Administradores: el rol va en app_metadata, que el usuario
-- no puede cambiar desde el navegador (user_metadata sí).
-- Para dar el rol a una cuenta ya registrada, ejecutar:
--
--   update auth.users
--   set raw_app_meta_data = raw_app_meta_data || '{"rol": "admin"}'
--   where email = 'admin@ejemplo.com';
--
-- El rol viaja en el token: la cuenta tiene que volver a
-- ingresar para que se aplique.
-- =========================================================

-- ---------- Tablas ----------

create table if not exists public.generos (
  id bigint primary key,
  nombre text not null unique
);

create table if not exists public.artistas (
  id bigint primary key,
  nombre text not null,
  genero text not null,
  imagen text not null,
  bio text,
  -- [{ "titulo": "Ruido blanco", "duracion": "3:24" }, ...]
  tracks jsonb not null default '[]'::jsonb
);

-- imagen null = sin imagen: el sitio muestra la de reemplazo.
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  titulo text not null,
  tipo text not null,
  precio integer not null check (precio >= 0),
  artista_id bigint not null references public.artistas (id),
  imagen text
);

-- Para bases creadas con la versión anterior del esquema:
-- id pasa a ser autoincremental e imagen, opcional.
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'productos'
      and column_name = 'id' and is_identity = 'YES'
  ) then
    alter table public.productos alter column id add generated by default as identity;
  end if;
end $$;

alter table public.productos alter column imagen drop not null;

create table if not exists public.seguidos (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  artista_id bigint not null references public.artistas (id) on delete cascade,
  creado_en timestamptz not null default now(),
  primary key (user_id, artista_id)
);

-- opcion vacía ('') = producto sin opciones (por ejemplo, entradas).
create table if not exists public.carrito_items (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  producto_id bigint not null references public.productos (id) on delete cascade,
  opcion text not null default '',
  cantidad integer not null check (cantidad between 1 and 10),
  creado_en timestamptz not null default now(),
  primary key (user_id, producto_id, opcion)
);

-- ---------- Seguridad (RLS) ----------

-- true si el token es de un administrador (ver arriba).
create or replace function public.es_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'rol') = 'admin', false)
$$;

alter table public.generos enable row level security;
alter table public.artistas enable row level security;
alter table public.productos enable row level security;
alter table public.seguidos enable row level security;
alter table public.carrito_items enable row level security;

grant select on public.generos, public.artistas, public.productos to anon, authenticated;
-- RLS decide quién puede usarlos: solo los administradores.
grant insert, update, delete on public.productos to authenticated;
grant select, insert, delete on public.seguidos to authenticated;
grant select, insert, update, delete on public.carrito_items to authenticated;

drop policy if exists "Catálogo público" on public.generos;
create policy "Catálogo público" on public.generos
  for select to anon, authenticated using (true);

drop policy if exists "Catálogo público" on public.artistas;
create policy "Catálogo público" on public.artistas
  for select to anon, authenticated using (true);

drop policy if exists "Catálogo público" on public.productos;
create policy "Catálogo público" on public.productos
  for select to anon, authenticated using (true);

drop policy if exists "Admin carga productos" on public.productos;
create policy "Admin carga productos" on public.productos
  for insert to authenticated with check ((select public.es_admin()));

drop policy if exists "Admin edita productos" on public.productos;
create policy "Admin edita productos" on public.productos
  for update to authenticated
  using ((select public.es_admin()))
  with check ((select public.es_admin()));

drop policy if exists "Admin borra productos" on public.productos;
create policy "Admin borra productos" on public.productos
  for delete to authenticated using ((select public.es_admin()));

drop policy if exists "Cada usuario ve sus seguidos" on public.seguidos;
create policy "Cada usuario ve sus seguidos" on public.seguidos
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Cada usuario sigue artistas" on public.seguidos;
create policy "Cada usuario sigue artistas" on public.seguidos
  for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "Cada usuario deja de seguir" on public.seguidos;
create policy "Cada usuario deja de seguir" on public.seguidos
  for delete to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Cada usuario maneja su carrito" on public.carrito_items;
create policy "Cada usuario maneja su carrito" on public.carrito_items
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- ---------- Imágenes de productos (Storage) ----------

-- Bucket público: las imágenes se leen por su URL sin token.
-- Storage rechaza archivos de más de 2 MB o de otro tipo.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('productos', 'productos', true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Borrar un archivo pide poder verlo (select) además de delete.
drop policy if exists "Admin ve imágenes de productos" on storage.objects;
create policy "Admin ve imágenes de productos" on storage.objects
  for select to authenticated
  using (bucket_id = 'productos' and (select public.es_admin()));

drop policy if exists "Admin sube imágenes de productos" on storage.objects;
create policy "Admin sube imágenes de productos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'productos' and (select public.es_admin()));

drop policy if exists "Admin borra imágenes de productos" on storage.objects;
create policy "Admin borra imágenes de productos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'productos' and (select public.es_admin()));

